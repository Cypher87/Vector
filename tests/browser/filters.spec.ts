test('distance requires a receiver position and accepts a custom radius', async ({ page, radar, isMobile }) => {
  radar.receiverPositionKnown = false;
  await page.goto('/');
  await expect(page.locator('.aircraft-map-marker')).toHaveCount(2);
  if (isMobile) await page.locator('.mobile-list-button').click();
  await page.locator('.filter-menu > summary').click();
  await openFilterGroup(page, 'distance');
  const distance = page.getByRole('combobox', { name: 'Distance from receiver', exact: true });
  await distance.selectOption('25');
  await expect(page.locator('.filter-warning')).toContainText('Receiver location is unknown');
  await expect(page.locator('.aircraft-map-marker')).toHaveCount(0);
  await expect(page.locator('.aircraft-row')).toHaveCount(0);
  await distance.selectOption('');
  await expect(page.locator('.aircraft-map-marker')).toHaveCount(2);
  await distance.selectOption('custom');
  const radius = page.getByRole('spinbutton', { name: 'Distance from receiver · To (km)', exact: true });
  await radius.fill('5');
  await radius.press('Tab');
  await expect(page.locator('.aircraft-map-marker')).toHaveCount(0);
  radar.receiverPositionKnown = true;
  await page.reload();
  await expect(page.locator('.aircraft-map-marker')).toHaveCount(1);
  if (isMobile) await page.locator('.mobile-list-button').click();
  await page.locator('.filter-menu > summary').click();
  await openFilterGroup(page, 'distance');
  await expect(radius).toHaveValue('5');
  await expect(page.locator('.filter-warning')).toHaveCount(0);
});
